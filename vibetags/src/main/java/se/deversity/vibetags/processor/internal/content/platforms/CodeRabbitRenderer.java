package se.deversity.vibetags.processor.internal.content.platforms;

import se.deversity.vibetags.processor.model.GuardrailModel;
import se.deversity.vibetags.processor.internal.content.Platform;
import se.deversity.vibetags.processor.internal.content.PlatformRenderer;
import se.deversity.vibetags.processor.internal.content.RenderingContext;
import se.deversity.vibetags.processor.internal.content.YamlMergeShape;

/**
 * PlatformRenderer for generating CodeRabbit's {@code .coderabbit.yaml} review configuration.
 * Emits {@code reviews.path_instructions} so CodeRabbit flags pull requests that violate the
 * VibeTags guardrails during AI review.
 */
public final class CodeRabbitRenderer implements PlatformRenderer {
    @Override
    public String render(GuardrailModel model, Platform platform, RenderingContext context) {
        StringBuilder sb = new StringBuilder(1024);
        sb.append("# AUTO-GENERATED BY VIBETAGS\n")
          .append(context.getGeneratedHeader())
          .append("# CodeRabbit AI review configuration. Do not edit manually.\n\n")
          .append("reviews:\n")
          .append("  high_level_summary: true\n")
          .append("  path_instructions:\n")
          .append("    - path: \"**/*.java\"\n")
          .append("      instructions: |\n");

        String block = GuardrailInstructionBlock.build(model);
        if (block.isBlank()) {
            sb.append("        No VibeTags guardrails are currently declared.\n");
        } else {
            sb.append("        Enforce the following VibeTags guardrails during review. ")
              .append("Flag any change that violates them:\n");
            sb.append(GuardrailInstructionBlock.indent(block.strip(), 8));
        }
        return sb.toString();
    }

    /**
     * Every module's guardrails go into the one {@code instructions:} block scalar written above,
     * rather than each module adding its own {@code path_instructions} entry for the same glob.
     * Sub-markers land inside the scalar and so read as provenance lines in the instruction text —
     * which is why they must stay indented to the scalar's column.
     */
    @Override
    public YamlMergeShape mergeShape() {
        return YamlMergeShape.appended("      instructions: |", 8,
            "        No VibeTags guardrails are currently declared.");
    }
}
