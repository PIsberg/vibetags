package se.deversity.vibetags.processor.internal.content.platforms;

import se.deversity.vibetags.processor.model.GuardrailModel;
import se.deversity.vibetags.processor.internal.content.Platform;
import se.deversity.vibetags.processor.internal.content.PlatformRenderer;
import se.deversity.vibetags.processor.internal.content.RenderingContext;

/**
 * PlatformRenderer for Gemini Code Assist's {@code .gemini/styleguide.md} review style guide.
 *
 * <p>This is a different product from the Gemini CLI, which reads {@code GEMINI.md} and is handled
 * by {@link GeminiRenderer}. Gemini Code Assist reviews pull requests on GitHub and takes its
 * per-repository rules from {@code .gemini/styleguide.md}, so the guardrails have to be restated
 * here or the reviewer never sees them.
 *
 * <p>Markdown, so {@code GuardrailFileWriter} gives the file HTML-comment markers and anything the
 * user wrote around them survives regeneration.
 */
public final class GeminiStyleguideRenderer implements PlatformRenderer {

    @Override
    public String render(GuardrailModel model, Platform platform, RenderingContext context) {
        StringBuilder sb = new StringBuilder(context.estimatedContentSize());
        sb.append("# ").append(context.getProjectName()).append(" review style guide\n")
          .append(context.getGeneratedHeader())
          .append("# AUTO-GENERATED BY VIBETAGS. Gemini Code Assist reads this file when reviewing a ")
          .append("pull request in this repository.\n\n")
          .append("## VibeTags guardrails\n\n");

        String block = GuardrailInstructionBlock.build(model);
        if (block.isBlank()) {
            sb.append("No VibeTags guardrails are currently declared.\n");
        } else {
            sb.append("Flag any change in this pull request that violates one of the following:\n\n")
              .append(block.strip()).append('\n');
        }
        return sb.toString();
    }
}
