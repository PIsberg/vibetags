package se.deversity.vibetags.processor.internal.content.platforms;

import se.deversity.vibetags.processor.model.TaggedElement;
import se.deversity.vibetags.processor.model.GuardrailModel;
import se.deversity.vibetags.processor.internal.content.FormatterRegistry;
import se.deversity.vibetags.processor.internal.content.Platform;
import se.deversity.vibetags.processor.internal.content.PlatformRenderer;
import se.deversity.vibetags.processor.internal.content.RenderingContext;

/**
 * A highly reusable PlatformRenderer for generating all standalone ignore/exclusion files.
 */
public final class IgnoreFileRenderer implements PlatformRenderer {
    @Override
    public String render(GuardrailModel model, Platform platform, RenderingContext context) {
        // A module with nothing to ignore contributes nothing, not a header.
        //
        // The header alone is non-blank, and ModuleSidecar.mergeFor() wraps every non-blank
        // contribution in its own module sub-markers. In a reactor, modules carrying no @AIIgnore
        // therefore each added a full "AUTO-GENERATED BY VIBETAGS / Generated by VibeTags /
        // <platform>-specific exclusion list" block to the merged file — three modules produced
        // three copies of the boilerplate around one real exclusion line. Returning empty lets the
        // merge skip them, which is what "this module has no opinion" should look like.
        if (model.ignore().isEmpty()) {
            return "";
        }
        StringBuilder sb = new StringBuilder(512);
        String name = getPlatformSpecificName(platform);
        sb.append("# AUTO-GENERATED BY VIBETAGS\n")
          .append(context.getGeneratedHeader())
          .append("# ").append(name).append("-specific exclusion list.\n");

        for (TaggedElement e : model.ignore()) {
            FormatterRegistry.ignore().format(e, sb, platform);
        }
        return sb.toString();
    }

    private static String getPlatformSpecificName(Platform platform) {
        switch (platform) {
            case CURSOR_IGNORE:      return "Cursor";
            case CLAUDE_IGNORE:      return "Claude";
            case COPILOT_IGNORE:     return "Copilot";
            case QWEN_IGNORE:        return "Qwen";
            case CODY_IGNORE:        return "Cody";
            case SUPERMAVEN_IGNORE:  return "Supermaven";
            case DOUBLE_IGNORE:      return "Double.bot";
            case CODEIUM_IGNORE:     return "Codeium";
            case ANTIGRAVITY_IGNORE: return "Antigravity AI";
            case AIDER_IGNORE:       return "Aider";
            case REPOMIX_IGNORE:     return "Repomix";
            case GITINGEST_IGNORE:   return "Gitingest";
            case GPT_IGNORE:         return "GPT context packer";
            case GHOSTCODER_IGNORE:  return "Ghostcoder";
            case PIECES_IGNORE:      return "Pieces for Developers";
            default:                 return "AI Platform";
        }
    }
}
