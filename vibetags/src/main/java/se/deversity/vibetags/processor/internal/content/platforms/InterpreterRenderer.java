package se.deversity.vibetags.processor.internal.content.platforms;

import se.deversity.vibetags.processor.model.TaggedElement;
import se.deversity.vibetags.processor.model.GuardrailModel;
import se.deversity.vibetags.processor.internal.content.AnnotationDescriptor;
import se.deversity.vibetags.processor.internal.content.AnnotationDescriptors;
import se.deversity.vibetags.processor.internal.content.Platform;
import se.deversity.vibetags.processor.internal.content.PlatformRenderer;
import se.deversity.vibetags.processor.internal.content.RenderingContext;
import se.deversity.vibetags.processor.internal.content.YamlMergeShape;

/**
 * PlatformRenderer for generating Open Interpreter profiles.
 */
public final class InterpreterRenderer implements PlatformRenderer {
    @Override
    public String render(GuardrailModel model, Platform platform, RenderingContext context) {
        StringBuilder sb = new StringBuilder();
        sb.append("# AUTO-GENERATED BY VIBETAGS\n")
          .append(context.getGeneratedHeader())
          .append("# Open Interpreter VibeTags guardrail profile. Do not edit manually.\n\n")
          .append("instructions: |\n");

        StringBuilder rules = new StringBuilder();
        for (AnnotationDescriptor descriptor : AnnotationDescriptors.ALL) {
            for (TaggedElement e : model.of(descriptor.type())) {
                descriptor.formatter().format(e, rules, Platform.INTERPRETER);
            }
        }

        if (rules.length() > 0) {
            sb.append("  ## Project Guardrails (Generated by VibeTags)\n\n");
            for (String line : rules.toString().split("\n", -1)) {
                sb.append("  ").append(line).append('\n');
            }
        }
        return sb.toString();
    }

    /** Every module's guardrails go into the one {@code instructions:} block scalar written above. */
    @Override
    public YamlMergeShape mergeShape() {
        return YamlMergeShape.appended("instructions: |", 2, "");
    }
}
