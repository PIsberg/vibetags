package se.deversity.vibetags.processor.internal.content.platforms;

import se.deversity.vibetags.processor.model.TaggedElement;
import se.deversity.vibetags.processor.model.GuardrailModel;
import se.deversity.vibetags.processor.internal.content.FormatterRegistry;
import se.deversity.vibetags.processor.internal.content.Platform;
import se.deversity.vibetags.processor.internal.content.PlatformRenderer;
import se.deversity.vibetags.processor.internal.content.RenderingContext;
import se.deversity.vibetags.processor.internal.content.YamlMergeShape;

/**
 * PlatformRenderer for generating Sweep config.
 */
public final class SweepRenderer implements PlatformRenderer {
    @Override
    public String render(GuardrailModel model, Platform platform, RenderingContext context) {
        StringBuilder sb = new StringBuilder();
        sb.append("# AUTO-GENERATED BY VIBETAGS\n")
          .append(context.getGeneratedHeader())
          .append("# Sweep AI code review rules. Do not edit manually.\n\n")
          .append("rules:\n");

        StringBuilder rules = new StringBuilder();
        for (TaggedElement e : model.locked()) FormatterRegistry.locked().format(e, rules, Platform.SWEEP);
        for (TaggedElement e : model.audit()) FormatterRegistry.audit().format(e, rules, Platform.SWEEP);
        for (TaggedElement e : model.draft()) FormatterRegistry.draft().format(e, rules, Platform.SWEEP);
        for (TaggedElement e : model.privacy()) FormatterRegistry.privacy().format(e, rules, Platform.SWEEP);
        for (TaggedElement e : model.core()) FormatterRegistry.core().format(e, rules, Platform.SWEEP);
        for (TaggedElement e : model.performance()) FormatterRegistry.performance().format(e, rules, Platform.SWEEP);
        for (TaggedElement e : model.contract()) FormatterRegistry.contract().format(e, rules, Platform.SWEEP);
        for (TaggedElement e : model.testDriven()) FormatterRegistry.testDriven().format(e, rules, Platform.SWEEP);
        for (TaggedElement e : model.idempotent()) FormatterRegistry.idempotent().format(e, rules, Platform.SWEEP);
        for (TaggedElement e : model.featureFlag()) FormatterRegistry.featureFlag().format(e, rules, Platform.SWEEP);
        for (TaggedElement e : model.secure()) FormatterRegistry.secure().format(e, rules, Platform.SWEEP);
        for (TaggedElement e : model.generated()) FormatterRegistry.generated().format(e, rules, Platform.SWEEP);
        for (TaggedElement e : model.loadBearing()) FormatterRegistry.loadBearing().format(e, rules, Platform.SWEEP);
        for (TaggedElement e : model.bannedApi()) FormatterRegistry.bannedApi().format(e, rules, Platform.SWEEP);
        for (TaggedElement e : model.threadAffinity()) FormatterRegistry.threadAffinity().format(e, rules, Platform.SWEEP);
        for (TaggedElement e : model.keepInSync()) FormatterRegistry.keepInSync().format(e, rules, Platform.SWEEP);

        if (rules.length() > 0) {
            sb.append(rules);
        } else {
            sb.append("  []\n");
        }
        return sb.toString();
    }

    /** Every module's entries go under the one {@code rules:} sequence written above. */
    @Override
    public YamlMergeShape mergeShape() {
        return YamlMergeShape.appended("rules:", 2, "  []");
    }
}
