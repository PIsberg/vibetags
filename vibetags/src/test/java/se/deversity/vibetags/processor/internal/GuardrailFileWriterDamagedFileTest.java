package se.deversity.vibetags.processor.internal;

import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * Repairing a damaged guardrail file has to be idempotent.
 *
 * <p>A guardrail file is hand-edited. Someone deletes the end marker while removing a paragraph,
 * or the file predates markers entirely, or a YAML header was opened and never closed. The writer
 * repairs each of those on the next build — and the repair is only half the contract. The other
 * half is that the build <em>after</em> the repair must recognise the file as already correct and
 * leave it alone.
 *
 * <p>It matters because of what a rewrite costs. Every write re-stats the file and invalidates its
 * cache entry, so a repair that never converges makes the file change on every single build: it
 * shows up in every {@code git status}, in every diff, and in every commit that touched anything
 * else. That is how people end up adding generated files to {@code .gitignore}, which is how the
 * guardrails stop being reviewed.
 *
 * <p>Each test therefore writes the damaged file, repairs it, and then asks the writer to do the
 * same work again with the same input — the second call must report that it wrote nothing, and the
 * bytes must be unchanged.
 *
 * <p>{@code GuardrailFileRecoveryEndToEndTest} covers what is preserved. This covers convergence.
 */
class GuardrailFileWriterDamagedFileTest {

    private static final String HEADER =
        "# Generated by VibeTags | https://github.com/PIsberg/vibetags\n";
    private static final String START = GuardrailFileWriter.MARKER_START_MD;
    private static final String END = GuardrailFileWriter.MARKER_END_MD;

    private static final String GENERATED = HEADER + "\n## Locked Files\n\n- `com.example.Ledger`\n";

    /** Writes {@code initial}, runs the writer twice with {@code GENERATED}, returns the outcome. */
    private record Outcome(boolean firstWrote, boolean secondWrote, String afterFirst, String afterSecond) {}

    private static Outcome repairTwice(Path file, String initial) throws IOException {
        Files.writeString(file, initial, StandardCharsets.UTF_8);
        GuardrailFileWriter writer = new GuardrailFileWriter(HEADER, null, null);

        boolean first = writer.writeFileIfChanged(file.toString(), GENERATED, true);
        String afterFirst = Files.readString(file, StandardCharsets.UTF_8);
        boolean second = writer.writeFileIfChanged(file.toString(), GENERATED, true);
        String afterSecond = Files.readString(file, StandardCharsets.UTF_8);
        return new Outcome(first, second, afterFirst, afterSecond);
    }

    @Test
    @DisplayName("a file whose end marker was deleted is repaired once, not on every build")
    void markersWithNoEndConverge(@TempDir Path dir) throws IOException {
        Path file = dir.resolve("CLAUDE.md");
        String damaged = "Hand-written project notes.\n\n"
            + START + "\n"
            + HEADER + "\n## Locked Files\n\n- `com.example.Old`\n";
        // No end marker: the file was edited and the closing comment went with the paragraph.

        Outcome outcome = repairTwice(file, damaged);

        assertTrue(outcome.firstWrote(), "the damaged file has to be repaired");
        assertFalse(outcome.secondWrote(),
            "the repaired file is already correct; rewriting it every build puts a generated file "
                + "in every commit");
        assertEquals(outcome.afterFirst(), outcome.afterSecond());
        assertTrue(outcome.afterFirst().contains("Hand-written project notes."),
            "content before the start marker is hand-authored and must survive: "
                + outcome.afterFirst());
        assertTrue(outcome.afterFirst().contains(END), "the repair adds the missing end marker");
        assertFalse(outcome.afterFirst().contains("com.example.Old"),
            "the stale generated block is replaced, not kept alongside the new one");
    }

    @Test
    @DisplayName("a marker-less legacy file is upgraded once, not on every build")
    void aLegacyFileConverges(@TempDir Path dir) throws IOException {
        Path file = dir.resolve("CLAUDE.md");
        // A file from before markers existed: the VibeTags header, no markers anywhere.
        Outcome outcome = repairTwice(file, HEADER + "\n## Locked Files\n\n- `com.example.Old`\n");

        assertTrue(outcome.firstWrote(), "a legacy file has to gain its markers");
        assertTrue(outcome.afterFirst().contains(START) && outcome.afterFirst().contains(END),
            "the upgrade is what adds the markers: " + outcome.afterFirst());
        assertFalse(outcome.secondWrote(),
            "once upgraded the file is ordinary; a second upgrade would rewrite it forever");
        assertEquals(outcome.afterFirst(), outcome.afterSecond());
    }

    @Test
    @DisplayName("a legacy file already holding this round's content is not rewritten at all")
    void aLegacyFileWhoseUpgradeChangesNothingIsSkipped(@TempDir Path dir) throws IOException {
        Path file = dir.resolve("CLAUDE.md");
        GuardrailFileWriter writer = new GuardrailFileWriter(HEADER, null, null);

        // Produce the upgraded form, then hand the writer exactly that as a pre-existing file.
        writer.writeFileIfChanged(file.toString(), GENERATED, true);
        String upgraded = Files.readString(file, StandardCharsets.UTF_8);

        Path second = dir.resolve("AGENTS.md");
        Files.writeString(second, upgraded, StandardCharsets.UTF_8);
        assertFalse(new GuardrailFileWriter(HEADER, null, null)
                .writeFileIfChanged(second.toString(), GENERATED, true),
            "a file that already holds byte-identical content is never rewritten, whichever path "
                + "the writer reached that conclusion by");
        assertEquals(upgraded, Files.readString(second, StandardCharsets.UTF_8));
    }

    @Test
    @DisplayName("a YAML header that was never closed is left alone rather than half-parsed")
    void anUnterminatedFrontMatterIsNotTreatedAsAHeader(@TempDir Path dir) throws IOException {
        Path file = dir.resolve("CLAUDE.md");
        // Three dashes, then no closing '---' anywhere. Parsing this as front matter would swallow
        // the rest of the file as a YAML block that was never meant to be one.
        String damaged = "---\ndescription: notes someone started and never finished\n\n"
            + "Some hand-written prose.\n";

        Outcome outcome = repairTwice(file, damaged);

        assertTrue(outcome.afterFirst().contains("Some hand-written prose."),
            "the prose is hand-authored content outside the markers: " + outcome.afterFirst());
        assertTrue(outcome.afterFirst().contains("description: notes someone started"),
            "an unterminated header is not one VibeTags wrote, so it is not rewritten either: "
                + outcome.afterFirst());
        assertFalse(outcome.secondWrote(), "and the result converges");
        assertEquals(outcome.afterFirst(), outcome.afterSecond());
    }

    @Test
    @DisplayName("a file VibeTags has never touched keeps everything and gains a block at the end")
    void aForeignFileIsAppendedToAndConverges(@TempDir Path dir) throws IOException {
        Path file = dir.resolve("AGENTS.md");
        String foreign = "# Team conventions\n\nAlways run the linter before pushing.\n";

        Outcome outcome = repairTwice(file, foreign);

        assertTrue(outcome.firstWrote());
        assertTrue(outcome.afterFirst().startsWith("# Team conventions"),
            "the existing document keeps its opening: " + outcome.afterFirst());
        assertTrue(outcome.afterFirst().contains("Always run the linter before pushing."));
        assertTrue(outcome.afterFirst().indexOf(START)
                > outcome.afterFirst().indexOf("Always run the linter"),
            "the generated block goes after what was already there");
        assertFalse(outcome.secondWrote());
        assertEquals(outcome.afterFirst(), outcome.afterSecond());
    }

    @Test
    @DisplayName("a marker standing on its own line inside the body is defused")
    void aStandaloneMarkerInTheContentIsNeutralised(@TempDir Path dir) throws IOException {
        // An @AIContext whose text is the marker on a line of its own would otherwise close the
        // block from inside, and on the next build everything after it would read as hand-authored
        // content to be preserved - so the file would grow a stale copy of itself every build.
        Path file = dir.resolve("CLAUDE.md");
        String hostile = HEADER + "\n## Context\n\n" + END + "\n\n- A rule.\n";

        GuardrailFileWriter writer = new GuardrailFileWriter(HEADER, null, null);
        assertTrue(writer.writeFileIfChanged(file.toString(), hostile, true));

        String written = Files.readString(file, StandardCharsets.UTF_8);
        assertEquals(1, markerLines(written, END),
            "exactly one end marker owns a line, or the block boundary is wherever the content "
                + "says it is: " + written);
        assertFalse(writer.writeFileIfChanged(file.toString(), hostile, true),
            "and the file converges rather than growing a copy of itself every build");
    }

    @Test
    @DisplayName("marker text quoted mid-sentence is left as the author wrote it")
    void anInlineMarkerMentionIsNotRewritten(@TempDir Path dir) throws IOException {
        // Only a marker that owns its line is a delimiter, so only that form needs defusing.
        // Rewriting a mid-sentence mention would corrupt documentation that talks about the
        // marker format - which is most of what a guardrail file about VibeTags would say.
        Path file = dir.resolve("CLAUDE.md");
        String prose = HEADER + "\n## Context\n\n- A rule mentioning " + END + " in its text.\n";

        GuardrailFileWriter writer = new GuardrailFileWriter(HEADER, null, null);
        assertTrue(writer.writeFileIfChanged(file.toString(), prose, true));

        String written = Files.readString(file, StandardCharsets.UTF_8);
        assertTrue(written.contains("- A rule mentioning " + END + " in its text."),
            "the sentence must survive verbatim: " + written);
        assertEquals(1, markerLines(written, END),
            "the quoted mention is not a delimiter, so the file still has exactly one: " + written);
        assertFalse(writer.writeFileIfChanged(file.toString(), prose, true),
            "and it converges");
    }

    /**
     * How many times {@code marker} stands alone on a line - the only form the writer treats as a
     * delimiter, so the only count that says where the block actually ends.
     */
    private static int markerLines(String content, String marker) {
        int count = 0;
        for (int i = GuardrailFileWriter.indexOfMarkerLine(content, marker, 0); i >= 0;
             i = GuardrailFileWriter.indexOfMarkerLine(content, marker, i + marker.length())) {
            count++;
        }
        return count;
    }

}
