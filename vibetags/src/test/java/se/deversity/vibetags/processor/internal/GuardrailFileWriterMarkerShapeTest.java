package se.deversity.vibetags.processor.internal;

import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * The exact file a marker write leaves, for each thing the file can be when the write finds it.
 *
 * <p>The writer's other tests say what must survive and what must change, mostly by asking whether
 * the file contains a line. They do not hold the whole file, so the blank lines between the
 * hand-written text and the block, the place the rendered front matter takes, and what a second
 * identical build does are open. Those are the diff a consumer sees in a committed file when the
 * merge is rearranged, and "nothing on the second build" is what keeps a no-op rebuild a no-op.
 * Each case compares the complete file, and where it matters also the second write.
 */
class GuardrailFileWriterMarkerShapeTest {

    private static final String HEADER = "# Generated by VibeTags | https://github.com/PIsberg/vibetags\n";
    private static final String START = "<!-- VIBETAGS-START -->";
    private static final String END = "<!-- VIBETAGS-END -->";
    private static final String FRONT_MATTER = "---\npaths: [\"**/Foo.java\"]\n---";

    @TempDir
    Path dir;

    private final GuardrailFileWriter writer = new GuardrailFileWriter(HEADER, null, null, null);

    private static String block(String body) {
        return START + "\n" + body + "\n" + END;
    }

    private Path file(String name, String existing) throws IOException {
        Path file = dir.resolve(name);
        if (existing != null) {
            Files.write(file, existing.getBytes(StandardCharsets.UTF_8));
        }
        return file;
    }

    private boolean write(Path file, String content, boolean hasNewRules) {
        return writer.writeFileIfChanged(file.toString(), content, hasNewRules);
    }

    private static String read(Path file) throws IOException {
        return Files.readString(file, StandardCharsets.UTF_8);
    }

    @Test
    @DisplayName("no file: the block is the file, under the rendered front matter when there is one")
    void anAbsentFileIsCreatedAsTheBlock() throws IOException {
        Path plain = file("CLAUDE.md", null);
        assertTrue(write(plain, "RULES A\n", true));
        assertEquals(block("RULES A") + "\n", read(plain));
        assertFalse(write(plain, "RULES A\n", true), "the same rendering again writes nothing");

        Path scoped = file("Foo.md", null);
        assertTrue(write(scoped, FRONT_MATTER + "\n\nRULES A", true));
        assertEquals(FRONT_MATTER + "\n\n" + block("RULES A") + "\n", read(scoped));
        assertFalse(write(scoped, FRONT_MATTER + "\n\nRULES A", true));
    }

    @Test
    @DisplayName("an empty file is the opt-in, and gets its block even from a round with no rules")
    void anEmptyFileGetsItsBlockWhateverTheRoundFound() throws IOException {
        Path empty = file("CLAUDE.md", "");
        assertTrue(write(empty, "RULES A", false));
        assertEquals(block("RULES A") + "\n", read(empty));

        Path blank = file("AGENTS.md", "\n\n  \n");
        assertFalse(write(blank, "RULES A", false), "a file with anything in it waits for a round that has rules");
        assertEquals("\n\n  \n", read(blank));
    }

    @Test
    @DisplayName("a hand-written file keeps its text and gets the block after one blank line")
    void aHandWrittenFileGetsTheBlockAppended() throws IOException {
        Path file = file("CLAUDE.md", "# Mine\n\nKeep me.\n\n\n");
        assertFalse(write(file, "RULES A", false));
        assertEquals("# Mine\n\nKeep me.\n\n\n", read(file), "a round with no rules leaves a hand-written file alone");

        assertTrue(write(file, "RULES A", true));
        assertEquals("# Mine\n\nKeep me.\n\n" + block("RULES A") + "\n", read(file));
        assertFalse(write(file, "RULES A", true), "the same rendering again writes nothing");
    }

    @Test
    @DisplayName("rendered front matter opens a hand-written file, and replaces a header already there")
    void renderedFrontMatterGoesFirst() throws IOException {
        Path headerless = file("Foo.md", "# Mine\n\nKeep me.\n");
        assertTrue(write(headerless, FRONT_MATTER + "\n\nRULES A", true));
        assertEquals(FRONT_MATTER + "\n\n# Mine\n\nKeep me.\n\n" + block("RULES A") + "\n", read(headerless));
        assertFalse(write(headerless, FRONT_MATTER + "\n\nRULES A", true));

        Path headed = file("Bar.md", "---\npaths: [\"old\"]\nalwaysApply: true\n---\n\n# Mine\n");
        assertTrue(write(headed, FRONT_MATTER + "\n\nRULES A", true));
        assertEquals(FRONT_MATTER + "\n\n# Mine\n\n" + block("RULES A") + "\n", read(headed));
    }

    @Test
    @DisplayName("a block between hand-written text is replaced where it stands")
    void aBlockIsReplacedWhereItStands() throws IOException {
        Path file = file("CLAUDE.md", "# Mine\n\nAbove.\n\n" + block("OLD RULES") + "\n\nBelow.\n\n\n");
        assertTrue(write(file, "NEW RULES", true));
        assertEquals("# Mine\n\nAbove.\n\n" + block("NEW RULES") + "\n\nBelow.\n", read(file));
        assertFalse(write(file, "NEW RULES", true), "the same rendering again writes nothing");
        assertFalse(write(file, "NEWER RULES", false), "and a round with no rules does not replace the block");
        assertEquals("# Mine\n\nAbove.\n\n" + block("NEW RULES") + "\n\nBelow.\n", read(file));
    }

    @Test
    @DisplayName("hash-marker files follow the same shape")
    void hashMarkerFilesFollowTheSameShape() throws IOException {
        Path file = file(".cursorrules", "mine\n\n# VIBETAGS-START\nOLD\n# VIBETAGS-END\n\nbelow\n");
        assertTrue(write(file, "NEW", true));
        assertEquals("mine\n\n# VIBETAGS-START\nNEW\n# VIBETAGS-END\n\nbelow\n", read(file));
        assertFalse(write(file, "NEW", true));
    }

    @Test
    @DisplayName("a file that differs only in line endings is left exactly as it is")
    void lineEndingsAloneAreNotADifference() throws IOException {
        String crlf = "# Mine\r\n\r\n" + START + "\r\nSAME\r\n" + END + "\r\n";
        Path file = file("CLAUDE.md", crlf);
        assertFalse(write(file, "SAME", true));
        assertEquals(crlf, read(file));
    }

    @Test
    @DisplayName("a byte order mark stays in front, and the block behind it is still found")
    void aByteOrderMarkIsKept() throws IOException {
        Path file = file("CLAUDE.md", "﻿" + block("OLD RULES") + "\n\nBelow.\n");
        assertTrue(write(file, "NEW RULES", true));
        assertEquals("﻿" + block("NEW RULES") + "\n\nBelow.\n", read(file));
        assertFalse(write(file, "NEW RULES", true));
    }

    @Test
    @DisplayName("only the first block is the block; a second one below is hand-written text")
    void onlyTheFirstBlockIsReplaced() throws IOException {
        Path file = file("CLAUDE.md", block("OLD RULES") + "\n\nMiddle.\n\n" + block("SECOND") + "\n");
        assertTrue(write(file, "NEW RULES", true));
        assertEquals(block("NEW RULES") + "\n\nMiddle.\n\n" + block("SECOND") + "\n", read(file));
    }

    @Test
    @DisplayName("a generated block that lost its end marker is rebuilt, once a round has rules")
    void aBlockThatLostItsEndIsRebuilt() throws IOException {
        String damaged = "# Mine\n\n" + START + "\n" + HEADER + "OLD RULES\nno end marker\n";
        Path file = file("CLAUDE.md", damaged);
        assertFalse(write(file, "NEW RULES", false));
        assertEquals(damaged, read(file), "a round with no rules repairs nothing");

        assertTrue(write(file, "NEW RULES", true));
        assertEquals("# Mine\n\n" + block("NEW RULES") + "\n", read(file));
        assertFalse(write(file, "NEW RULES", true));
    }

    @Test
    @DisplayName("a stray start marker with hand-written text after it leaves the file untouched")
    void aStrayStartMarkerLeavesTheFileUntouched() throws IOException {
        String stray = "# Mine\n\n" + START + "\nmy own text after a stray start\n";
        Path file = file("CLAUDE.md", stray);
        assertFalse(write(file, "NEW RULES", true));
        assertEquals(stray, read(file));
    }

    @Test
    @DisplayName("a pre-marker file is upgraded: the old block goes, the text around it stays")
    void aLegacyFileIsUpgradedToMarkers() throws IOException {
        String legacy = "# Mine\n\nKeep me.\n\n" + HEADER + "<project_guardrails>\n<x/>\n</project_guardrails>\n\nAfter legacy.\n";
        Path file = file("CLAUDE.md", legacy);
        assertFalse(write(file, "NEW RULES", false));
        assertEquals(legacy, read(file), "a round with no rules upgrades nothing");

        assertTrue(write(file, "NEW RULES", true));
        String upgraded = read(file);
        assertTrue(upgraded.startsWith("# Mine\n\nKeep me.\n\nAfter legacy.\n"), upgraded);
        assertTrue(upgraded.endsWith("\n" + block("NEW RULES") + "\n"), upgraded);
        assertFalse(upgraded.contains("project_guardrails"), upgraded);

        Path generatedOnly = file("AGENTS.md", "# AUTO-GENERATED AI RULES\n" + HEADER + "old rule line\n");
        assertTrue(write(generatedOnly, "NEW RULES", true));
        assertEquals(block("NEW RULES") + "\n", read(generatedOnly), "a file that was all ours becomes the block alone");
    }

    /**
     * #1162. The upgrade joined the hand-written text with its trailing newline still on, so it left
     * two blank lines above the block; the next build found the block, rebuilt the file with one,
     * and wrote it again. An upgrade must leave the file the next build leaves alone.
     */
    @Test
    @DisplayName("a legacy upgrade is a fixed point: the next build writes nothing")
    void aLegacyUpgradeIsAFixedPoint() throws IOException {
        String legacyBlock = HEADER + "<project_guardrails>\n<x/>\n</project_guardrails>\n";

        Path around = file("CLAUDE.md", "# Mine\n\nKeep me.\n\n" + legacyBlock + "\nAfter legacy.\n");
        assertTrue(write(around, "NEW RULES", true));
        assertEquals("# Mine\n\nKeep me.\n\nAfter legacy.\n\n" + block("NEW RULES") + "\n", read(around),
            "one blank line between the hand-written text and the block");
        assertFalse(write(around, "NEW RULES", true), "the build after the upgrade must not write again");

        Path onlyAfter = file("GEMINI.md", legacyBlock + "\nAfter legacy.\n");
        assertTrue(write(onlyAfter, "NEW RULES", true));
        assertFalse(write(onlyAfter, "NEW RULES", true), "text only below the legacy block: " + read(onlyAfter));

        Path trailingBlanks = file("QWEN.md", "# Mine\n\n\n\n" + legacyBlock + "\n\n");
        assertTrue(write(trailingBlanks, "NEW RULES", true));
        assertFalse(write(trailingBlanks, "NEW RULES", true), "blank lines around the legacy block: " + read(trailingBlanks));

        // The ordinary replace trims the head of the file; the legacy strip already does (see #1163).
        Path leadingBlanks = file("AGENTS.md", "\n\n# Mine\n\n" + legacyBlock);
        assertTrue(write(leadingBlanks, "NEW RULES", true));
        assertFalse(write(leadingBlanks, "NEW RULES", true), "blank lines at the top of the file: " + read(leadingBlanks));
    }

    @Test
    @DisplayName("a marker line inside the rendered body is defused, and the write is still a fixed point")
    void aMarkerLineInTheBodyIsDefused() throws IOException {
        Path file = file("CLAUDE.md", block("OLD RULES") + "\n");
        String body = "before\n" + END + "\nafter\n" + START + "\nend";
        assertTrue(write(file, body, true));
        assertEquals(START + "\nbefore\n<!--​ VIBETAGS-END -->\nafter\n<!--​ VIBETAGS-START -->\nend\n" + END + "\n",
            read(file));
        assertFalse(write(file, body, true), "a body that could close its own block would grow the file on every build");
    }
}
