package se.deversity.vibetags.processor.internal;

import ch.qos.logback.classic.Level;
import ch.qos.logback.classic.Logger;
import ch.qos.logback.classic.LoggerContext;
import ch.qos.logback.classic.spi.ILoggingEvent;
import ch.qos.logback.core.AppenderBase;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.TestInfo;
import org.junit.jupiter.api.io.TempDir;
import org.slf4j.LoggerFactory;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.attribute.FileTime;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * A file found current is recorded in the write cache only with attributes that describe the bytes
 * compared (#1145).
 *
 * <p>In a parallel reactor every module writes the root {@code CLAUDE.md}. The writer stats the
 * file, reads it, finds it already holds its rendering, stats it again and, when the two stats
 * agree, records its body's hash with the first stat's size and mtime. An A-B-A replacement fools
 * that: file A is statted, B (another module's write, holding this writer's body) is read, and A
 * again is there for the second stat, with A's size and mtime. On Windows the file key is
 * {@code null} and two writes in one clock tick share an mtime, so nothing told A from A'. The
 * cache then vouched for B's body while the file held A's, and the write that would have fixed it
 * was skipped: {@code WriteCacheCrossInstanceAsyncTest} caught that shape twice on windows-latest.
 *
 * <p>Here the other writer is played at the writer's own DEBUG events: {@code write.read} between
 * the first stat and the read, and the {@code identical-bytes} skip between the read and the second
 * stat. Both replacements write in place and the mtime is restored, so the second stat matches the
 * first on every OS, file key included, and the race is the same without the timing.
 */
@DisplayName("GuardrailFileWriter and a file replaced while it is read")
class GuardrailFileWriterReplacedDuringReadTest {

    private static final String HEADER = "# Generated by VibeTags | https://github.com/PIsberg/vibetags\n";
    private static final String EMPTY_BLOCK =
        GuardrailFileWriter.MARKER_START_MD + "\n" + GuardrailFileWriter.MARKER_END_MD + "\n";
    private static final String MINE = "- guardrail from module b, the longer of the two bodies\n";
    private static final String THEIRS = "- guardrail from module a\n";

    private Logger logger;

    /** A logger of this test's own, so the parallel suite cannot mix another test's events in. */
    @BeforeEach
    void captureDebugLog(TestInfo testInfo) {
        LoggerContext context = (LoggerContext) LoggerFactory.getILoggerFactory();
        logger = context.getLogger(GuardrailFileWriterReplacedDuringReadTest.class.getName() + "."
            + testInfo.getDisplayName());
        logger.setLevel(Level.DEBUG);
    }

    @Test
    @DisplayName("an A-B-A replacement around the read is not recorded as current")
    void aFileReplacedAroundTheReadIsNotVouchedFor(@TempDir Path dir) throws IOException {
        Path file = dir.resolve("CLAUDE.md");
        byte[] theirs = rendered(dir.resolve("a"), THEIRS);
        byte[] mine = rendered(dir.resolve("b"), MINE);
        Files.write(file, theirs);
        FileTime theirTime = Files.getLastModifiedTime(file);
        WriteCache cache = new WriteCache(dir.resolve(WriteCache.DEFAULT_FILE_NAME));

        try (Replacer ignored = Replacer.attach(logger, file, mine, theirs, theirTime)) {
            assertFalse(new GuardrailFileWriter(HEADER, null, logger, cache)
                    .writeFileIfChanged(file.toString(), MINE, true),
                "precondition: the writer read its own body and found the file current");
        }

        assertEquals(new String(theirs, StandardCharsets.UTF_8), Files.readString(file),
            "precondition: the other module's bytes are what the file holds now");
        assertFalse(cache.isUnchanged(file, MINE),
            "the cache vouched for a body the file does not hold, so the next write would be skipped");
    }

    @Test
    @DisplayName("a file found current is still recorded, whatever its encoding holds")
    void aCurrentFileIsStillRecorded(@TempDir Path dir) throws IOException {
        // The check counts the UTF-8 bytes of what was read; a byte order mark, CRLF line ends and
        // characters of two, three and four bytes must all count as the bytes on disk.
        String body = "- caf\u00e9 \u20ac \uD83D\uDE80 r\u00e8gle\n";
        Path file = dir.resolve("CLAUDE.md");
        byte[] current = rendered(dir.resolve("c"), body);
        String crlf = "\uFEFF" + new String(current, StandardCharsets.UTF_8).replace("\n", "\r\n");
        Files.writeString(file, crlf, StandardCharsets.UTF_8);
        WriteCache cache = new WriteCache(dir.resolve(WriteCache.DEFAULT_FILE_NAME));

        assertFalse(new GuardrailFileWriter(HEADER, null, logger, cache)
                .writeFileIfChanged(file.toString(), body, true),
            "precondition: the file already holds the rendering");
        assertTrue(cache.isUnchanged(file, body),
            "a file that nothing replaced is recorded, so the next build takes the cache fast path");
    }

    /** The bytes the writer leaves in a CLAUDE.md that held an empty block, for {@code body}. */
    private byte[] rendered(Path scratch, String body) throws IOException {
        Files.createDirectories(scratch);
        Path file = scratch.resolve("CLAUDE.md");
        Files.writeString(file, EMPTY_BLOCK);
        assertTrue(new GuardrailFileWriter(HEADER, null, null).writeFileIfChanged(file.toString(), body, true));
        return Files.readAllBytes(file);
    }

    /** Plays the other module: B in place at the read, A back in place with A's mtime before the second stat. */
    private static final class Replacer extends AppenderBase<ILoggingEvent> implements AutoCloseable {
        private final Logger logger;
        private final Path file;
        private final byte[] read;
        private final byte[] restored;
        private final FileTime restoredTime;

        private Replacer(Logger logger, Path file, byte[] read, byte[] restored, FileTime restoredTime) {
            this.logger = logger;
            this.file = file;
            this.read = read.clone();
            this.restored = restored.clone();
            this.restoredTime = restoredTime;
        }

        static Replacer attach(Logger logger, Path file, byte[] read, byte[] restored, FileTime restoredTime) {
            Replacer replacer = new Replacer(logger, file, read, restored, restoredTime);
            replacer.setContext(logger.getLoggerContext());
            replacer.start();
            logger.addAppender(replacer);
            return replacer;
        }

        @Override
        protected void append(ILoggingEvent event) {
            String message = event.getFormattedMessage();
            try {
                if (message.startsWith("write.read ")) {
                    Files.write(file, read);
                } else if (message.startsWith("write.skip ") && message.contains("reason=identical-bytes")) {
                    Files.write(file, restored);
                    Files.setLastModifiedTime(file, restoredTime);
                }
            } catch (IOException e) {
                throw new UncheckedIOException(e);
            }
        }

        @Override
        public void close() {
            logger.detachAppender(this);
            stop();
        }
    }
}
