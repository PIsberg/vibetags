package se.deversity.vibetags.processor.internal.content;

import org.junit.jupiter.api.Test;

import java.util.List;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNull;

/**
 * {@link MarkdownSectionMerge}: one Markdown document from several source sets' bodies (issue
 * #841), and a decline wherever the bodies are not a shape it knows.
 */
class MarkdownSectionMergeTest {

    private static final String HEADER = "# AUTO-GENERATED AI RULES\n# Generated by VibeTags\n\n";
    private static final String POINTER = "Guardrails for test code are in TESTING.md.";

    @Test
    void sharedSectionsHoldBothSourceSetsEntriesAndThePointerComesLast() {
        String main = HEADER
            + "## LOCKED FILES (DO NOT EDIT)\n- **a.Main**: wire format\n\n"
            + "## SECURITY-CRITICAL CODE\nDo not weaken:\n\n- **a.Sec**: boundary";
        String test = HEADER
            + "## LOCKED FILES (DO NOT EDIT)\n- **a.MainTest**: wire format\n\n"
            + "## SECURITY-CRITICAL CODE\nDo not weaken:\n\n- **a.SecTest**: boundary\n\n" + POINTER;

        assertEquals(HEADER
                + "## LOCKED FILES (DO NOT EDIT)\n- **a.Main**: wire format\n- **a.MainTest**: wire format\n\n"
                + "## SECURITY-CRITICAL CODE\nDo not weaken:\n\n- **a.Sec**: boundary\n- **a.SecTest**: boundary\n\n"
                + POINTER,
            MarkdownSectionMerge.merge(List.of(main, test)),
            "one header, each heading and intro once, main entries first, the pointer at the end");
    }

    @Test
    void thePointerGoesLastEvenWhenTheTestSourceSetsLastSectionIsMidDocument() {
        // A test round with only locked classes ends on LOCKED, which the merged document follows
        // with the main round's later sections. Left in place, the pointer would sit between them.
        String main = HEADER + "## LOCKED\n- a\n\n## CONTEXTUAL RULES\n- c";
        String test = HEADER + "## LOCKED\n- b\n\n" + POINTER;

        assertEquals(HEADER + "## LOCKED\n- a\n- b\n\n## CONTEXTUAL RULES\n- c\n\n" + POINTER,
            MarkdownSectionMerge.merge(List.of(main, test)));
    }

    @Test
    void aSectionOnlyTheTestSourceSetHasLandsBeforeTheNextSharedOne() {
        String main = HEADER + "## LOCKED\n- a\n\n## SECURITY\n- s";
        String test = HEADER + "## TEST ISOLATION\n- t\n\n## SECURITY\n- s2";

        assertEquals(HEADER + "## LOCKED\n- a\n\n## TEST ISOLATION\n- t\n\n## SECURITY\n- s\n- s2",
            MarkdownSectionMerge.merge(List.of(main, test)));
    }

    @Test
    void thePointerAfterAnEmptyLastSectionIsNotTakenForItsIntro() {
        String main = HEADER + "## SECURITY\n- s\n\n## CONTEXTUAL RULES\n- c";
        String test = HEADER + "## SECURITY\n- s2\n\n## CONTEXTUAL RULES\n\n" + POINTER;

        assertEquals(HEADER + "## SECURITY\n- s\n- s2\n\n## CONTEXTUAL RULES\n- c\n\n" + POINTER,
            MarkdownSectionMerge.merge(List.of(main, test)));
    }

    @Test
    void aBodyWithNoSectionsKeepsItsLeadOnceAndThePointerLast() {
        // .qwen/commands/refactor.md: a header and one paragraph, then the pointer.
        String main = "# /refactor command\n# AUTO-GENERATED BY VIBETAGS\n\nRefactor the current selection.";
        String test = main + "\n\n" + POINTER;

        assertEquals(test, MarkdownSectionMerge.merge(List.of(main, test)));
    }

    @Test
    void headingPerEntryBodiesAppendTheTestSourceSetsEntries() {
        // CONVENTIONS.md: every entry is its own #### heading, and no section is shared.
        String main = "# X CONVENTIONS\n\nIntro.\n\n#### LOCKED: a.Main\n- **Reason**: r\n\n#### CONTEXT: a.Main\n- **Focus**: f";
        String test = "# X CONVENTIONS\n\nIntro.\n\n#### LOCKED: a.MainTest\n- **Reason**: r";

        assertEquals(main + "\n\n#### LOCKED: a.MainTest\n- **Reason**: r",
            MarkdownSectionMerge.merge(List.of(main, test)));
    }

    @Test
    void aBulletIsComparedWithItsNestedLinesAsOneBlock() {
        // The transitive appendix nests rules under a package bullet. Two source sets naming the
        // same package with different rules must keep both, not collapse on the shared first line.
        String section = "## Inherited Guardrails (dependencies)\n\nThese come from packages.\n\n";
        String main = HEADER + section + "- `com.dep`\n  - @AILocked: A";
        String test = HEADER + section + "- `com.dep`\n  - @AILocked: B";

        assertEquals(HEADER + section + "- `com.dep`\n  - @AILocked: A\n- `com.dep`\n  - @AILocked: B",
            MarkdownSectionMerge.merge(List.of(main, test)));
    }

    @Test
    void aHashCommentPointerStaysLast() {
        // A hash-marker file gets the pointer as a comment line, which reads as a level-1 heading.
        String main = "# RULES\n\n## LOCKED\n- a";
        String test = "# RULES\n\n## LOCKED\n- b\n\n# " + POINTER;

        assertEquals("# RULES\n\n## LOCKED\n- a\n- b\n\n# " + POINTER,
            MarkdownSectionMerge.merge(List.of(main, test)));
    }

    @Test
    void identicalBodiesAreWrittenOnceByteForByte() {
        String body = HEADER
            + "## LOCKED FILES (DO NOT EDIT)\n\n"
            + "## 🔒 PII / PRIVACY GUARDRAILS\nThe following elements handle PII.\nNEVER log them.\n\n"
            + "* `a.Owner.email` - never log\n  - Required Checks: redaction\n\n"
            + "## SCOPED RULES\nEvery other guardrail lives elsewhere.";

        assertEquals(body, MarkdownSectionMerge.merge(List.of(body, body)));
    }

    @Test
    void declinesWhatItCannotProveSafe() {
        String main = HEADER + "## LOCKED\nIntro one.\n\n- a";
        assertNull(MarkdownSectionMerge.merge(List.of(main, "# OTHER HEADER\n\n## LOCKED\n- b")),
            "a different header is another renderer version's scaffold");
        assertNull(MarkdownSectionMerge.merge(List.of(main, HEADER + "## LOCKED\nIntro two.\n\n- b")),
            "the same section with a different intro");
        assertNull(MarkdownSectionMerge.merge(List.of(main, HEADER + "## LOCKED\n- b\nnot indented")),
            "a lazy continuation line is not a shape any renderer writes");
    }

    @Test
    void oneBodyIsReturnedAsIs() {
        assertEquals("anything", MarkdownSectionMerge.merge(List.of("anything")));
        assertNull(MarkdownSectionMerge.merge(List.of()));
    }
}
