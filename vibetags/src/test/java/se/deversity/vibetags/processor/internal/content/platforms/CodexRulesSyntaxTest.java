package se.deversity.vibetags.processor.internal.content.platforms;

import org.junit.jupiter.api.Test;
import se.deversity.vibetags.processor.internal.content.Platform;
import se.deversity.vibetags.processor.internal.content.RenderingContext;
import se.deversity.vibetags.processor.model.GuardrailModel;

import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * {@code .codex/rules/vibetags.rules} must be a file Codex can load (issue #969).
 *
 * <p>Codex's {@code prefix_rule} takes {@code pattern} as a list of command tokens. Every rule was
 * emitted as {@code prefix_rule("ls", "allow")}, and Codex refuses to load the whole file over
 * the first one: {@code codex execpolicy check --rules .codex/rules/vibetags.rules ls} reported
 * "Type of parameter `pattern` doesn't match, expected `list`, actual `string`" on line 5. A
 * rules file that fails to parse grants and guards nothing, while the file's presence still
 * reads as a configured policy.
 *
 * <p>There is no Starlark parser on the test classpath, so this pins the call shape Codex
 * accepts, checked against codex-cli 0.162.1: keyword arguments, {@code pattern} a list of string
 * tokens, {@code decision} one of the three values the docs list. It is a proxy: the
 * {@code codex-rules} job in {@code build.yml} loads the committed file with the pinned Codex CLI
 * itself (#970), and that job, not this regex, is what notices if Codex changes what it accepts.
 */
class CodexRulesSyntaxTest {

    private static final RenderingContext CONTEXT = new RenderingContext(
        "Test Project", "# Generated by VibeTags | https://github.com/PIsberg/vibetags\n", Set.of());

    private static final Pattern PREFIX_RULE = Pattern.compile(
        "prefix_rule\\(pattern=\\[(\"[^\"]+\"(?:, \"[^\"]+\")*)\\], decision=\"(allow|prompt|forbidden)\"\\)");

    private static List<String> lines() {
        return new CodexRenderer().render(GuardrailModel.EMPTY, Platform.CODEX_RULES, CONTEXT)
            .lines().toList();
    }

    @Test
    void everyStatementIsAPrefixRuleWithAListPattern() {
        List<String> statements = lines().stream()
            .filter(l -> !l.isBlank() && !l.startsWith("#"))
            .toList();

        assertFalse(statements.isEmpty(), "the rules file rendered no rules at all");
        for (String statement : statements) {
            assertTrue(PREFIX_RULE.matcher(statement).matches(),
                "Codex cannot parse \"" + statement + "\": prefix_rule takes pattern=[\"token\", ...] "
                    + "and decision=\"allow|prompt|forbidden\", and one bad line rejects the whole file");
        }
    }

    @Test
    void keepsTheSevenCommandDecisions() {
        Map<String, String> decisions = new LinkedHashMap<>();
        for (String line : lines()) {
            Matcher m = PREFIX_RULE.matcher(line);
            if (m.matches()) {
                decisions.put(m.group(1), m.group(2));
            }
        }

        Map<String, String> expected = new LinkedHashMap<>();
        expected.put("\"ls\"", "allow");
        expected.put("\"cat\"", "allow");
        expected.put("\"grep\"", "allow");
        expected.put("\"mvn\"", "prompt");
        expected.put("\"npm\"", "prompt");
        expected.put("\"git\"", "prompt");
        expected.put("\"rm\"", "prompt");
        assertEquals(expected, decisions);
    }

    @Test
    void headerIsASingleComment() {
        String header = lines().get(0);

        assertEquals("# Generated by VibeTags | https://github.com/PIsberg/vibetags", header,
            "the generated header already carries its '# ', so prefixing another rendered '# # Generated'");
    }
}
