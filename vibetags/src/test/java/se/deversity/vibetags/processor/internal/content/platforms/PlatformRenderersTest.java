    @Test
    void locksReportRenderer_rendersLockedElementsAndEscapesJson() {
        TaggedElement mockElement = mock(TaggedElement.class);
        when(mockElement.path()).thenReturn("com.example.\"Class\"\n");
        when(mockElement.kind()).thenReturn(ElementTag.CLASS);
        AILocked annotation = mock(AILocked.class);
        when(annotation.reason()).thenReturn("Test reason with \\ backslash");
        when(mockElement.annotation(AILocked.class)).thenReturn(annotation);

        SourceLocation loc = new SourceLocation("src/Main.java", 10, 20);

        GuardrailModel model = GuardrailModel.builder()
                .add(AILocked.class, mockElement)
                .lockedPosition(mockElement, loc)
                .build();

        LocksReportRenderer renderer = new LocksReportRenderer();
        String output = renderer.render(model, Platform.VOID, ctx);

        assertTrue(output.contains("{\"type\":\"format\",\"version\":1}"));
        assertTrue(output.contains("\"element\":\"com.example.\\\"Class\\\"\\n\""));
        assertTrue(output.contains("\"reason\":\"Test reason with \\\\ backslash\""));
        assertTrue(output.contains("\"file\":\"src/Main.java\""));
        assertTrue(output.contains("\"startLine\":10"));
        assertTrue(output.contains("\"endLine\":20"));
        assertTrue(output.contains("\"kind\":\"CLASS\""));
    }

